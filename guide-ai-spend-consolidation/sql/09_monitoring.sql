CREATE OR REPLACE VIEW AI_SPEND.CONTROL.V_REPORT_HEALTH AS
WITH last_run AS (
 SELECT PLATFORM_KEY,REPORT_NAME,COMPLETED_AT,STATUS,ERROR_CLASS,WATERMARK_TO
 FROM AI_SPEND.CONTROL.PULL_RUN_LOG
 QUALIFY ROW_NUMBER() OVER (PARTITION BY PLATFORM_KEY,REPORT_NAME ORDER BY STARTED_AT DESC,RUN_ID DESC) = 1
), last_success AS (
 SELECT PLATFORM_KEY,REPORT_NAME,MAX(COMPLETED_AT) AS LAST_SUCCESS_AT,
        MAX(WATERMARK_TO) AS LAST_WATERMARK
 FROM AI_SPEND.CONTROL.PULL_RUN_LOG WHERE STATUS = 'SUCCEEDED' GROUP BY 1,2
), native AS (
 SELECT PLATFORM_KEY,REPORT_NAME,MAX(LAST_SEEN_TS) AS LAST_SEEN_TS
 FROM AI_SPEND.RAW.V_SNOWFLAKE_NATIVE_USAGE GROUP BY 1,2
)
SELECT expected.PLATFORM_KEY,expected.REPORT_NAME,expected.SOURCE_KIND,
       success.LAST_SUCCESS_AT,success.LAST_WATERMARK,native.LAST_SEEN_TS,
       recent.ERROR_CLASS,
       CASE WHEN expected.SOURCE_KIND = 'NATIVE' AND native.LAST_SEEN_TS IS NULL THEN 'NO_OBSERVED_USAGE'
            WHEN expected.SOURCE_KIND = 'NATIVE' AND DATEDIFF('hour',native.LAST_SEEN_TS,CURRENT_TIMESTAMP()) > p.EXPECTED_LAG_HOURS THEN 'VERIFY_QUIET_OR_STALE'
            WHEN expected.SOURCE_KIND = 'NATIVE' THEN 'OBSERVED_RECENT_USAGE'
            WHEN recent.STATUS = 'FAILED' THEN 'FAILED'
            WHEN success.LAST_SUCCESS_AT IS NULL THEN 'NEVER_PULLED'
            WHEN recent.STATUS <> 'SUCCEEDED' THEN 'RUN_NOT_SUCCEEDED'
            WHEN expected.REPORT_NAME <> 'SEATS' AND success.LAST_WATERMARK IS NULL THEN 'MISSING_WATERMARK'
            WHEN DATEDIFF('hour',success.LAST_SUCCESS_AT,CURRENT_TIMESTAMP()) > p.EXPECTED_LAG_HOURS THEN 'STALE'
            -- Worked GitHub report stops three UTC dates back; its exclusive
            -- watermark can be almost 72 hours old during normal publication.
            -- Keep pull freshness separate from that source publication delay.
            WHEN expected.REPORT_NAME <> 'SEATS' AND DATEDIFF('hour',success.LAST_WATERMARK,CURRENT_TIMESTAMP()) >
                 IFF(expected.PLATFORM_KEY = 'GITHUB_COPILOT' AND expected.REPORT_NAME = 'USER_USAGE',
                     GREATEST(p.EXPECTED_LAG_HOURS,72),p.EXPECTED_LAG_HOURS) THEN 'SOURCE_BEHIND'
            ELSE 'HEALTHY' END AS REPORT_STATUS
FROM AI_SPEND.CONTROL.REPORT_REGISTRY expected
JOIN AI_SPEND.CONTROL.PLATFORM_REGISTRY p ON p.PLATFORM_KEY = expected.PLATFORM_KEY
LEFT JOIN last_run recent ON recent.PLATFORM_KEY = expected.PLATFORM_KEY AND recent.REPORT_NAME = expected.REPORT_NAME
LEFT JOIN last_success success ON success.PLATFORM_KEY = expected.PLATFORM_KEY AND success.REPORT_NAME = expected.REPORT_NAME
LEFT JOIN native ON native.PLATFORM_KEY = expected.PLATFORM_KEY AND native.REPORT_NAME = expected.REPORT_NAME
WHERE expected.IS_REQUIRED;

CREATE OR REPLACE VIEW AI_SPEND.CONTROL.V_PIPELINE_HEALTH AS
WITH reports AS (
 SELECT PLATFORM_KEY,COUNT(*) AS EXPECTED_REPORTS,
        COUNT_IF(REPORT_STATUS NOT IN ('HEALTHY','OBSERVED_RECENT_USAGE')) AS REPORTS_NEEDING_REVIEW,
        MIN(LAST_SUCCESS_AT) AS LAST_SUCCESS_AT,
        LISTAGG(REPORT_NAME || ':' || REPORT_STATUS, ', ') WITHIN GROUP (ORDER BY REPORT_NAME) AS REPORT_DETAILS
 FROM AI_SPEND.CONTROL.V_REPORT_HEALTH GROUP BY PLATFORM_KEY
), latest_runs AS (
 SELECT PLATFORM_KEY,REPORT_NAME,RUN_ID
 FROM AI_SPEND.CONTROL.PULL_RUN_LOG WHERE STATUS = 'SUCCEEDED'
 QUALIFY ROW_NUMBER() OVER (PARTITION BY PLATFORM_KEY,REPORT_NAME ORDER BY COMPLETED_AT DESC,RUN_ID DESC) = 1
), drift AS (
 -- Inspect latest published runs, including bad subjects/dates, BEFORE filtering.
 SELECT u.PLATFORM_KEY,COUNT(*) AS UNSHREDDABLE_ROWS
 FROM AI_SPEND.SHAPED.V_EXTERNAL_USAGE u
 JOIN latest_runs r ON r.RUN_ID = u.RUN_ID AND r.PLATFORM_KEY = u.PLATFORM_KEY AND r.REPORT_NAME = u.REPORT_NAME
 WHERE u.USAGE_DATE IS NULL OR NULLIF(TRIM(u.SUBJECT_KEY),'') IS NULL
 GROUP BY u.PLATFORM_KEY
), facts AS (
 SELECT PLATFORM_KEY,MAX(USAGE_DATE) AS LATEST_USAGE_DATE,COUNT(*) AS FACT_ROWS,
        COUNT_IF(COST_STATUS NOT IN ('PRICED','NOT_APPLICABLE')) AS UNPRICED_ROWS,
        100*COUNT_IF(IDENTITY_CONFIDENCE = 'NONE' AND ENTITY_KIND = 'PERSON')
           /NULLIF(COUNT_IF(ENTITY_KIND = 'PERSON'),0) AS UNRESOLVED_PCT
 FROM AI_SPEND.SHAPED.UNIFIED_AI_USAGE GROUP BY PLATFORM_KEY
)
SELECT p.PLATFORM_KEY,p.DISPLAY_NAME,p.IS_ACTIVE,p.COST_MODEL,
       p.SUPPORTS_USER_GRAIN,p.SUPPORTS_USER_COST,r.LAST_SUCCESS_AT,
       r.REPORT_DETAILS,p.EXPECTED_LAG_HOURS,f.LATEST_USAGE_DATE,f.FACT_ROWS,
       COALESCE(d.UNSHREDDABLE_ROWS,0) AS UNSHREDDABLE_ROWS,
       COALESCE(f.UNPRICED_ROWS,0) AS UNPRICED_ROWS,f.UNRESOLVED_PCT,
       CASE WHEN NOT p.IS_ACTIVE THEN 'INACTIVE'
            WHEN r.EXPECTED_REPORTS IS NULL THEN 'REPORTS_NOT_REGISTERED'
            WHEN COALESCE(d.UNSHREDDABLE_ROWS,0) > 0 THEN 'SHAPE_DRIFT'
            WHEN r.REPORTS_NEEDING_REVIEW > 0 THEN 'REPORT_REVIEW_REQUIRED'
            WHEN COALESCE(f.UNPRICED_ROWS,0) > 0 THEN 'UNPRICED_COST'
            WHEN f.UNRESOLVED_PCT > 25 THEN 'IDENTITY_GAP'
            WHEN f.LATEST_USAGE_DATE IS NULL THEN 'VERIFY_EMPTY_OR_UNIMPLEMENTED'
            WHEN DATEDIFF('hour',f.LATEST_USAGE_DATE::TIMESTAMP_NTZ,CURRENT_TIMESTAMP()) >
                 IFF(p.PLATFORM_KEY = 'GITHUB_COPILOT',GREATEST(p.EXPECTED_LAG_HOURS,72),p.EXPECTED_LAG_HOURS) + 24 THEN 'FACT_BEHIND'
            ELSE 'HEALTHY' END AS HEALTH_STATUS
FROM AI_SPEND.CONTROL.PLATFORM_REGISTRY p
LEFT JOIN reports r ON r.PLATFORM_KEY = p.PLATFORM_KEY
LEFT JOIN drift d ON d.PLATFORM_KEY = p.PLATFORM_KEY
LEFT JOIN facts f ON f.PLATFORM_KEY = p.PLATFORM_KEY;

SELECT PLATFORM_KEY,HEALTH_STATUS,REPORT_DETAILS,LATEST_USAGE_DATE,UNPRICED_ROWS,
       UNSHREDDABLE_ROWS,UNRESOLVED_PCT
FROM AI_SPEND.CONTROL.V_PIPELINE_HEALTH WHERE HEALTH_STATUS <> 'HEALTHY';
-- Native last usage is evidence of activity, not source completeness. A quiet
-- native service needs investigation, not a fabricated FAILED/zero-usage verdict.

SELECT PLATFORM_KEY,REPORT_NAME,ERROR_CLASS,COUNT(*) AS OCCURRENCES,MAX(STARTED_AT) AS MOST_RECENT
FROM AI_SPEND.CONTROL.PULL_RUN_LOG
WHERE STATUS = 'FAILED' AND STARTED_AT >= DATEADD('day',-30,CURRENT_TIMESTAMP())
GROUP BY PLATFORM_KEY,REPORT_NAME,ERROR_CLASS;

SELECT PLATFORM_KEY,SUBJECT_KEY,ENTITY_KIND,CURRENCY_CODE,COUNT(*) AS UNRESOLVED_ROWS,
       SUM(COST_AMOUNT) AS UNATTRIBUTED_COST
FROM AI_SPEND.SHAPED.UNIFIED_AI_USAGE WHERE IDENTITY_CONFIDENCE = 'NONE'
GROUP BY PLATFORM_KEY,SUBJECT_KEY,ENTITY_KIND,CURRENCY_CODE;

SELECT PLATFORM_KEY,CURRENCY_CODE,ENTITY_KIND,TOTAL_ROWS,UNRESOLVED_PCT,UNPRICED_ROWS
FROM AI_SPEND.SHAPED.V_IDENTITY_QUALITY;

SELECT NAME,SCHEMA_NAME,STATE,STATE_MESSAGE,REFRESH_START_TIME,REFRESH_END_TIME
FROM TABLE(AI_SPEND.INFORMATION_SCHEMA.DYNAMIC_TABLE_REFRESH_HISTORY(
 NAME_PREFIX => 'AI_SPEND.', DATA_TIMESTAMP_START => DATEADD('day',-2,CURRENT_TIMESTAMP()),
 RESULT_LIMIT => 10000
))
QUALIFY ROW_NUMBER() OVER (PARTITION BY DATABASE_NAME,SCHEMA_NAME,NAME ORDER BY REFRESH_START_TIME DESC) = 1;
-- Compare against SHOW DYNAMIC TABLES as well: no refresh record is not healthy.
SHOW DYNAMIC TABLES IN DATABASE AI_SPEND;

SELECT NAME,SCHEDULED_TIME,STATE,ERROR_CODE,ERROR_MESSAGE
FROM TABLE(AI_SPEND.INFORMATION_SCHEMA.TASK_HISTORY(
 TASK_NAME => 'TASK_PULL_GITHUB_COPILOT',
 SCHEDULED_TIME_RANGE_START => DATEADD('day',-7,CURRENT_TIMESTAMP()),
 SCHEDULED_TIME_RANGE_END => CURRENT_TIMESTAMP(),RESULT_LIMIT => 10000
)) WHERE DATABASE_NAME = 'AI_SPEND' AND SCHEMA_NAME = 'CONTROL'
ORDER BY SCHEDULED_TIME DESC LIMIT 50;

SELECT TO_DATE(START_TIME) AS USAGE_DATE,SPLIT_PART(QUERY_TAG,':',2) AS PLATFORM_KEY,
       COUNT(*) AS QUERY_COUNT,SUM(CREDITS_USED_CLOUD_SERVICES) AS CLOUD_SERVICES_CREDITS
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
WHERE QUERY_TAG LIKE 'AI_SPEND:%' AND START_TIME >= DATEADD('day',-30,CURRENT_TIMESTAMP())
GROUP BY 1,2;
SELECT TO_DATE(START_TIME) AS USAGE_DATE,SUM(CREDITS_USED_COMPUTE) AS COMPUTE_CREDITS,
       SUM(CREDITS_USED) AS TOTAL_CREDITS
FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
WHERE WAREHOUSE_NAME = 'AI_SPEND_WH' AND START_TIME >= DATEADD('day',-30,CURRENT_TIMESTAMP())
GROUP BY 1;

