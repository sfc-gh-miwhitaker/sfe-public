/* Cross-platform AI spend consolidation - normalization
   Pair-programmed by SE Community + Cortex Code
   Expires: 2026-11-09

   Publish only complete successful report partitions. Preserve every row within
   the chosen snapshot BEFORE aggregating. Event-stream adapters must first dedup
   by vendor event ID (not person/day), then publish complete partition snapshots.
   Billing fields are independent of person attribution. Unknown cost stays NULL.
*/
USE ROLE AI_SPEND_RL;
USE WAREHOUSE AI_SPEND_WH;

CREATE OR REPLACE VIEW AI_SPEND.SHAPED.V_CURRENT_REPORT_PARTITIONS AS
SELECT s.PLATFORM_KEY, s.REPORT_NAME, s.PARTITION_DATE, s.RUN_ID, s.RECORD_COUNT,
       r.COMPLETED_AT
FROM AI_SPEND.CONTROL.REPORT_SNAPSHOT s
JOIN AI_SPEND.CONTROL.PULL_RUN_LOG r
  ON r.RUN_ID = s.RUN_ID AND r.PLATFORM_KEY = s.PLATFORM_KEY
 AND r.REPORT_NAME = s.REPORT_NAME AND r.STATUS = 'SUCCEEDED'
QUALIFY ROW_NUMBER() OVER (
  PARTITION BY s.PLATFORM_KEY, s.REPORT_NAME, s.PARTITION_DATE
  ORDER BY r.COMPLETED_AT DESC, s.RUN_ID DESC
) = 1;

CREATE OR REPLACE VIEW AI_SPEND.SHAPED.V_SHRED_GITHUB_COPILOT AS
SELECT PLATFORM_KEY, REPORT_NAME, BILLING_CONTEXT,
       TRY_TO_DATE(RECORD:day::VARCHAR) AS USAGE_DATE,
       RECORD:user_login::VARCHAR AS SUBJECT_KEY,
       RECORD:user_login::VARCHAR AS SUBJECT_DISPLAY_NAME,
       'PERSON'::VARCHAR AS ENTITY_KIND,
       TRY_TO_DECIMAL(RECORD:ai_credits_used::VARCHAR, 38, 6) AS NATIVE_QTY,
       TRY_TO_NUMBER(RECORD:code_acceptance_activity_count::VARCHAR) AS ACTIVITY_COUNT,
       RECORD:ai_adoption_phase::VARCHAR AS VENDOR_ENGAGEMENT_LABEL,
       'ACTIVITY_ONLY'::VARCHAR AS COST_BASIS,
       NULL::NUMBER(38,6) AS BILLABLE_NATIVE_QTY,
       NULL::NUMBER(38,6) AS REPORTED_COST_AMOUNT,
       NULL::VARCHAR AS REPORTED_CURRENCY,
       RUN_ID, PULLED_AT, SOURCE_FILE, SOURCE_ROW_NUMBER, LOADED_AT
FROM AI_SPEND.RAW.LANDING_AI_USAGE
WHERE PLATFORM_KEY = 'GITHUB_COPILOT' AND REPORT_NAME = 'USER_USAGE';

