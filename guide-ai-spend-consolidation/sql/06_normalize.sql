-- FULL deliberately: the native branch reads shared ACCOUNT_USAGE views, and
-- this reference does not assume they support incremental change tracking.
-- CREATE OR ALTER avoids replacement on unchanged reruns; definition updates
-- still need a refresh and verification before publishing the changed columns.
CREATE OR ALTER DYNAMIC TABLE AI_SPEND.SHAPED.UNIFIED_AI_USAGE
TARGET_LAG = '12 hours'
WAREHOUSE = AI_SPEND_WH
REFRESH_MODE = FULL
INITIALIZE = ON_CREATE
AS
WITH external_current AS (
    SELECT u.PLATFORM_KEY, u.REPORT_NAME, u.BILLING_CONTEXT, u.USAGE_DATE,
           u.SUBJECT_KEY, u.SUBJECT_DISPLAY_NAME, u.ENTITY_KIND, u.NATIVE_QTY,
           u.ACTIVITY_COUNT, u.VENDOR_ENGAGEMENT_LABEL, u.COST_BASIS,
           u.BILLABLE_NATIVE_QTY, u.REPORTED_COST_AMOUNT, u.REPORTED_CURRENCY, u.LOADED_AT
    FROM AI_SPEND.SHAPED.V_EXTERNAL_USAGE u
    JOIN AI_SPEND.SHAPED.V_CURRENT_REPORT_PARTITIONS s
      ON s.PLATFORM_KEY = u.PLATFORM_KEY AND s.REPORT_NAME = u.REPORT_NAME
     AND s.PARTITION_DATE = u.USAGE_DATE AND s.RUN_ID = u.RUN_ID
    WHERE u.USAGE_DATE IS NOT NULL AND NULLIF(TRIM(u.SUBJECT_KEY), '') IS NOT NULL
),
all_usage AS (
    SELECT PLATFORM_KEY, REPORT_NAME, BILLING_CONTEXT, USAGE_DATE, SUBJECT_KEY,
           SUBJECT_DISPLAY_NAME, ENTITY_KIND, NATIVE_QTY, ACTIVITY_COUNT,
           VENDOR_ENGAGEMENT_LABEL, COST_BASIS, BILLABLE_NATIVE_QTY,
           REPORTED_COST_AMOUNT, REPORTED_CURRENCY, LOADED_AT
    FROM external_current
    UNION ALL
    SELECT PLATFORM_KEY, REPORT_NAME, BILLING_CONTEXT, USAGE_DATE, SUBJECT_KEY,
           SUBJECT_DISPLAY_NAME, ENTITY_KIND, CREDITS::NUMBER(38,6), REQUEST_COUNT,
           NULL::VARCHAR, 'BILLABLE_NATIVE', CREDITS::NUMBER(38,6),
           NULL::NUMBER(38,6), NULL::VARCHAR, LAST_SEEN_TS::TIMESTAMP_TZ
    FROM AI_SPEND.RAW.V_SNOWFLAKE_NATIVE_USAGE
),
-- Aggregate all breakdown/event rows only after complete-snapshot selection.
daily AS (
    SELECT PLATFORM_KEY, REPORT_NAME, BILLING_CONTEXT, USAGE_DATE, SUBJECT_KEY,
           MAX(SUBJECT_DISPLAY_NAME) AS SUBJECT_DISPLAY_NAME, ENTITY_KIND,
           SUM(NATIVE_QTY) AS NATIVE_QTY, SUM(ACTIVITY_COUNT) AS ACTIVITY_COUNT,
           MAX(VENDOR_ENGAGEMENT_LABEL) AS VENDOR_ENGAGEMENT_LABEL, COST_BASIS,
           IFF(COUNT_IF(BILLABLE_NATIVE_QTY IS NULL) > 0, NULL, SUM(BILLABLE_NATIVE_QTY)) AS BILLABLE_NATIVE_QTY,
           IFF(COUNT_IF(REPORTED_COST_AMOUNT IS NULL) > 0, NULL, SUM(REPORTED_COST_AMOUNT)) AS REPORTED_COST_AMOUNT,
           REPORTED_CURRENCY, MAX(LOADED_AT) AS LOADED_AT
    FROM all_usage
    GROUP BY PLATFORM_KEY, REPORT_NAME, BILLING_CONTEXT, USAGE_DATE, SUBJECT_KEY,
             ENTITY_KIND, COST_BASIS, REPORTED_CURRENCY
),
identities AS (
    SELECT u.PLATFORM_KEY, u.SUBJECT_KEY, u.USAGE_DATE, m.PERSON_KEY,
           m.CONFIDENCE, m.DEPARTMENT, m.COST_CENTER, m.BUSINESS_UNIT, m.ENTITY_KIND
    FROM (SELECT DISTINCT PLATFORM_KEY, SUBJECT_KEY, USAGE_DATE FROM daily) u
    JOIN AI_SPEND.CONTROL.IDENTITY_MAP m
      ON m.PLATFORM_KEY = u.PLATFORM_KEY AND m.SUBJECT_KEY = u.SUBJECT_KEY
     AND u.USAGE_DATE BETWEEN m.VALID_FROM AND m.VALID_TO
    QUALIFY ROW_NUMBER() OVER (PARTITION BY u.PLATFORM_KEY, u.SUBJECT_KEY, u.USAGE_DATE
      ORDER BY m.VALID_FROM DESC, m.UPDATED_AT DESC, m.PERSON_KEY) = 1
),
rates AS (
    SELECT u.PLATFORM_KEY, u.USAGE_DATE, r.UNIT_COST, r.CURRENCY_CODE,
           COUNT(*) OVER (PARTITION BY u.PLATFORM_KEY, u.USAGE_DATE) AS RATE_MATCHES
    FROM (SELECT DISTINCT PLATFORM_KEY, USAGE_DATE FROM daily) u
    JOIN AI_SPEND.CONTROL.PLATFORM_RATE r
      ON r.PLATFORM_KEY = u.PLATFORM_KEY AND u.USAGE_DATE BETWEEN r.VALID_FROM AND r.VALID_TO
    QUALIFY ROW_NUMBER() OVER (PARTITION BY u.PLATFORM_KEY, u.USAGE_DATE
      ORDER BY r.VALID_FROM DESC, r.UPDATED_AT DESC) = 1
)
SELECT u.USAGE_DATE, u.PLATFORM_KEY, p.DISPLAY_NAME AS PLATFORM_DISPLAY_NAME,
       u.REPORT_NAME, u.BILLING_CONTEXT, p.COST_MODEL, u.SUBJECT_KEY, u.SUBJECT_DISPLAY_NAME,
       COALESCE(m.PERSON_KEY, 'UNRESOLVED:' || u.PLATFORM_KEY || ':' || u.SUBJECT_KEY) AS PERSON_KEY,
       COALESCE(m.CONFIDENCE, 'NONE') AS IDENTITY_CONFIDENCE,
       m.DEPARTMENT, m.COST_CENTER, m.BUSINESS_UNIT,
       u.NATIVE_QTY, p.NATIVE_UNIT, u.ACTIVITY_COUNT,
       CASE WHEN p.COST_MODEL = 'SEAT' THEN NULL
            WHEN u.COST_BASIS = 'REPORTED_CURRENCY' AND REGEXP_LIKE(u.REPORTED_CURRENCY, '[A-Z]{3}')
              THEN u.REPORTED_COST_AMOUNT
            WHEN u.COST_BASIS = 'BILLABLE_NATIVE' AND r.RATE_MATCHES = 1 AND r.UNIT_COST >= 0
                 AND REGEXP_LIKE(r.CURRENCY_CODE, '[A-Z]{3}')
              THEN u.BILLABLE_NATIVE_QTY * r.UNIT_COST
       END::NUMBER(38,6) AS COST_AMOUNT,
       CASE WHEN u.COST_BASIS = 'REPORTED_CURRENCY' THEN u.REPORTED_CURRENCY
            WHEN u.COST_BASIS = 'BILLABLE_NATIVE' AND r.RATE_MATCHES = 1 THEN r.CURRENCY_CODE
       END AS CURRENCY_CODE,
       u.VENDOR_ENGAGEMENT_LABEL, p.SUPPORTS_USER_COST, u.LOADED_AT AS LAST_LOADED_AT,
       CASE WHEN u.ENTITY_KIND IN ('SERVICE', 'SYSTEM', 'UNKNOWN') THEN u.ENTITY_KIND
            WHEN u.ENTITY_KIND = 'PERSON' THEN COALESCE(m.ENTITY_KIND, 'PERSON')
            ELSE 'UNKNOWN' END AS ENTITY_KIND,
       u.COST_BASIS,
       CASE WHEN p.COST_MODEL = 'SEAT' OR u.COST_BASIS = 'ACTIVITY_ONLY' THEN 'NOT_APPLICABLE'
            WHEN u.COST_BASIS = 'REPORTED_CURRENCY' AND u.REPORTED_COST_AMOUNT IS NOT NULL
                 AND REGEXP_LIKE(u.REPORTED_CURRENCY, '[A-Z]{3}') THEN 'PRICED'
            WHEN u.COST_BASIS = 'BILLABLE_NATIVE' AND r.RATE_MATCHES = 1 AND r.UNIT_COST >= 0
                 AND u.BILLABLE_NATIVE_QTY IS NOT NULL AND REGEXP_LIKE(r.CURRENCY_CODE, '[A-Z]{3}') THEN 'PRICED'
            WHEN u.COST_BASIS = 'BILLABLE_NATIVE' AND r.RATE_MATCHES IS NULL THEN 'MISSING_RATE'
            ELSE 'INVALID_COST_INPUT' END AS COST_STATUS
FROM daily u
JOIN AI_SPEND.CONTROL.PLATFORM_REGISTRY p ON p.PLATFORM_KEY = u.PLATFORM_KEY AND p.IS_ACTIVE
LEFT JOIN identities m ON m.PLATFORM_KEY = u.PLATFORM_KEY AND m.SUBJECT_KEY = u.SUBJECT_KEY AND m.USAGE_DATE = u.USAGE_DATE
LEFT JOIN rates r ON r.PLATFORM_KEY = u.PLATFORM_KEY AND r.USAGE_DATE = u.USAGE_DATE;

CREATE OR REPLACE VIEW AI_SPEND.SHAPED.V_IDENTITY_QUALITY AS
SELECT PLATFORM_KEY, PLATFORM_DISPLAY_NAME, CURRENCY_CODE, ENTITY_KIND,
       COUNT(*) AS TOTAL_ROWS, COUNT(DISTINCT PERSON_KEY) AS DISTINCT_SUBJECTS,
       COUNT_IF(IDENTITY_CONFIDENCE = 'NONE') AS UNRESOLVED_ROWS,
       ROUND(100 * COUNT_IF(IDENTITY_CONFIDENCE = 'NONE') / NULLIF(COUNT(*), 0), 2) AS UNRESOLVED_PCT,
       SUM(IFF(IDENTITY_CONFIDENCE = 'NONE', COST_AMOUNT, NULL)) AS UNRESOLVED_COST_AMOUNT,
       COUNT_IF(COST_STATUS NOT IN ('PRICED', 'NOT_APPLICABLE')) AS UNPRICED_ROWS
FROM AI_SPEND.SHAPED.UNIFIED_AI_USAGE
GROUP BY PLATFORM_KEY, PLATFORM_DISPLAY_NAME, CURRENCY_CODE, ENTITY_KIND;

SELECT PLATFORM_KEY, COST_MODEL, NATIVE_UNIT, CURRENCY_CODE, ENTITY_KIND, COST_STATUS,
       COUNT(*) AS ROWS_IN_FACT, SUM(NATIVE_QTY) AS TOTAL_NATIVE_QTY,
       SUM(COST_AMOUNT) AS TOTAL_COST_AMOUNT, MAX(USAGE_DATE) AS LATEST_DATE
FROM AI_SPEND.SHAPED.UNIFIED_AI_USAGE
GROUP BY PLATFORM_KEY, COST_MODEL, NATIVE_UNIT, CURRENCY_CODE, ENTITY_KIND, COST_STATUS;
