   source fields and grain; merely activating the registry must NOT activate an
   illustrative parser. COST_BASIS is one of ACTIVITY_ONLY, BILLABLE_NATIVE,
   REPORTED_CURRENCY, UNKNOWN. A report exposing total consumption including a
   seat allowance is ACTIVITY_ONLY unless a separate billable amount is proven.

   Period reports (M365 D7/D28/D90/D180) need period-grain reporting, not repeated
   daily totals. Box dated CSV: retain Date + user + product/capability/category
   breakdown rows; AI_EVENTS dedup on event ID and never carry AI Unit charges.
   Cursor/Claude: cast reported decimal cents / 100 here, not in the adapter;
   retain explicit currency. API/project subjects use ENTITY_KIND = SERVICE.
*/
